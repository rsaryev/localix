import { join } from 'node:path'

import { runBun } from './bun-child'
import { writeGeneratedFile } from './generated-file'
import type { MiniAppKit } from './kit'
import { PLUGIN_KIT_TYPECHECK } from './kit-layout'

/**
 * Type-check a USER plugin against the declarations the kit ships, and give the editor the same
 * view.
 *
 * The defect: a user plugin was bundled and run, never type-checked, and bundling erases types.
 * One plugin published `{ strategy: 'replace', text }` where the SDK takes `{ strategy, bindings }`
 * and every check passed; the tab crashed at render. And with no `tsconfig.json` the editor's
 * language server answered every import with "Cannot find module", so real errors
 * drowned in false ones. One generated `tsconfig.json` fixes both: it maps each importable module to
 * its declaration in the kit, `mini_app_build` checks with it, and the language server reads it too,
 * so the agent sees the same errors while editing that the build reports.
 */

const TYPECHECK_TIMEOUT_MS = 120_000
/** Enough to fix in one pass; the rest are usually the same mistake repeated. */
const MAX_REPORTED = 25

export interface TypeDiagnostic {
  file: string | null
  line: number | null
  column: number | null
  code: number
  message: string
}

/** The plugin's `tsconfig.json`: updated when the kit moves, without needless editor reloads. */
export async function writeMiniAppTsconfig(kit: MiniAppKit, pluginDir: string): Promise<void> {
  const paths = Object.fromEntries(
    Object.entries(kit.manifest.typePaths).map(([specifier, file]) => [
      specifier,
      [join(kit.dir, file)],
    ]),
  )
  const config = {
    compilerOptions: {
      target: 'ES2022',
      lib: ['ES2023', 'DOM', 'DOM.Iterable'],
      module: 'ESNext',
      moduleResolution: 'Bundler',
      jsx: 'react-jsx',
      strict: true,
      // Off since the kit was declared by export NAME only (`any`), when a callback handed to a kit
      // component lost its contextual type and `noImplicitAny` blamed the plugin for the gap.
      // The kit now carries its components' real props and the SDK's own imports, so
      // that gap is closed; a module whose types do not compile still falls back to names
      // (`stage-plugin-kit-declarations.mjs`), which is why this stays off. The rest of `strict`
      // applies.
      noImplicitAny: false,
      noEmit: true,
      isolatedModules: true,
      // The kit's declarations reference modules a plugin cannot import; their bodies are not the
      // plugin's to check.
      skipLibCheck: true,
      types: ['bun'],
      typeRoots: [join(kit.dir, 'types', 'node_modules', '@types')],
      paths,
    },
    include: ['**/*.ts', '**/*.tsx'],
    exclude: ['dist', 'node_modules'],
  }
  const header = '// Generated by Localix when the plugin kit changes; edits are overwritten.\n'
  await writeGeneratedFile(
    join(pluginDir, 'tsconfig.json'),
    `${header}${JSON.stringify(config, null, 2)}\n`,
    'tsconfig.json',
  )
}

export function formatTypeDiagnostic(d: TypeDiagnostic): string {
  const at = d.file ? `${d.file}${d.line ? `:${d.line}:${d.column}` : ''} ` : ''
  return `${at}TS${d.code}: ${d.message.replaceAll('\n', ' ')}`
}

/** One line per type error (capped), empty when the plugin type-checks. */
export async function typecheckMiniApp(kit: MiniAppKit, pluginDir: string): Promise<string[]> {
  await writeMiniAppTsconfig(kit, pluginDir)
  const run = await runBun(
    [join(kit.dir, PLUGIN_KIT_TYPECHECK), pluginDir],
    pluginDir,
    TYPECHECK_TIMEOUT_MS,
  )
  const diagnostics: TypeDiagnostic[] = []
  for (const line of run.stdout.split('\n')) {
    if (!line.startsWith('{')) continue
    try {
      diagnostics.push(JSON.parse(line) as TypeDiagnostic)
    } catch {
      // A truncated last line of a huge report; the count below still says there were more.
    }
  }
  if (diagnostics.length === 0 && run.code !== 0) {
    return [`the type checker failed to run: ${run.output.trim().split('\n').slice(-3).join(' ')}`]
  }
  const lines = diagnostics.slice(0, MAX_REPORTED).map(formatTypeDiagnostic)
  if (diagnostics.length > MAX_REPORTED) {
    lines.push(`… and ${diagnostics.length - MAX_REPORTED} more type errors`)
  }
  return lines
}
