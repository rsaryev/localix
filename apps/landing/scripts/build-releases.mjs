import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { writeFileAtomic } from './atomic-write.mjs'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(__dirname, '../../..')
const defaultChangelog = path.join(repoRoot, 'CHANGELOG.md')
const defaultOutFile = path.resolve(__dirname, '../src/generated/releases.ts')

/** A published release heading: `## v<version> — <YYYY-MM-DD>`, and nothing else after the date. */
const RELEASE_HEADING = /^## v(?<version>\S+) — (?<date>\d{4}-\d{2}-\d{2})$/u
const GROUPS = { Added: 'added', Changed: 'changed', Fixed: 'fixed', Removed: 'removed' }

function firstSentence(paragraph) {
  const text = paragraph
    .join(' ')
    .replaceAll(/\[([^\]]+)\]\([^)]*\)/gu, '$1')
    .replaceAll(/\*\*([^*]+)\*\*/gu, '$1')
    .replaceAll(/`([^`]+)`/gu, '$1')
    .replaceAll(/\s+/gu, ' ')
    .trim()
  const end = text.search(/\.(?:\s|$)/u)
  return end === -1 ? text : text.slice(0, end + 1)
}

/**
 * The releases the homepage lists, read from the changelog so the page cannot drift from it: each
 * dated version, the first sentence of its introduction and how many entries each group holds.
 * Headings that are not a plain date (a draft, an old "published" note) are left out.
 */
export function parseReleases(changelog) {
  const releases = []
  let current = null
  let group = null
  let intro = null
  for (const line of changelog.split('\n')) {
    if (line.startsWith('## ')) {
      const match = line.match(RELEASE_HEADING)
      current = match
        ? { ...match.groups, summary: '', added: 0, changed: 0, fixed: 0, removed: 0 }
        : null
      if (current) releases.push(current)
      group = null
      intro = current ? [] : null
      continue
    }
    if (!current) continue
    if (line.startsWith('### ')) {
      group = GROUPS[line.slice(4).trim()] ?? null
      if (intro) current.summary = firstSentence(intro)
      intro = null
      continue
    }
    if (intro) {
      if (line.trim()) intro.push(line)
      else if (intro.length) {
        current.summary = firstSentence(intro)
        intro = null
      }
      continue
    }
    if (group && line.startsWith('- ')) current[group] += 1
  }
  return releases.map(({ version, date, summary, added, changed, fixed, removed }) => ({
    version,
    date,
    summary,
    added,
    changed,
    fixed,
    removed,
  }))
}

export async function buildReleases({
  changelog = defaultChangelog,
  outFile = defaultOutFile,
} = {}) {
  const releases = parseReleases(await fs.readFile(changelog, 'utf8'))
  const body = `// Generated by scripts/build-releases.mjs from CHANGELOG.md. Do not edit.
export interface Release {
  version: string
  date: string
  summary: string
  added: number
  changed: number
  fixed: number
  removed: number
}

export const releases: Release[] = ${JSON.stringify(releases, null, 2)}
`
  await writeFileAtomic(outFile, body)
  return releases
}

if (import.meta.main) {
  const releases = await buildReleases()
  console.log(`[releases:gen] ${releases.length} releases → apps/landing/src/generated/releases.ts`)
}
