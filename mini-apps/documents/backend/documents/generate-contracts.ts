import { z } from 'zod'
import { documentLayoutSchema, type DocumentLayout } from '@localixai/mini-app-sdk/document-layout'

/**
 * Agnostic document-GENERATION contracts (the reverse of extraction). The generator
 * turns model-authored content into a real binary deliverable: Markdown → **docx** or
 * **pdf**, and rows / a Markdown table → **xlsx**. Bytes in, bytes out — it knows
 * nothing about chat, the agent loop, media persistence, or the UI. Both the
 * `POST /rpc/documents/
 * generate` consume the SAME generator through the documents service.
 */

/** The binary deliverable formats the generator can produce. */
export const GENERATE_FORMATS = ['docx', 'xlsx', 'pdf'] as const
export type GenerateFormat = (typeof GENERATE_FORMATS)[number]

/**
 * Input to the generator. `content` is interpreted per format:
 * - `docx` / `pdf`: Markdown (headings, paragraphs, lists, tables, code, quotes).
 * - `xlsx`: EITHER a Markdown pipe table OR JSON — an array of arrays, an array of
 *   objects, or `{ columns, rows }`.
 * `filename` is an optional caller hint for the suggested output name (extension is
 * forced to match `format`).
 */
export interface GenerateInput {
  format: GenerateFormat
  content: string
  /** Optional preferred base name for the produced file (extension normalised to format). */
  filename?: string
  layout?: DocumentLayout
}

/** The generator's raw output: the encoded bytes + how to name/serve them. */
export interface GeneratedDocument {
  /** The produced file bytes (a real .docx/.xlsx zip or a %PDF- document). */
  bytes: Uint8Array
  /** Canonical media type for the format (OOXML / PDF). */
  mediaType: string
  /** A sensible file name, e.g. `report.docx` (derived from `filename` or the content). */
  suggestedFilename: string
}

/**
 * The AGNOSTIC generation port. One implementation encodes all three formats; the
 * documents service delegates to it.
 */
export interface DocumentGenerator {
  generate(input: GenerateInput): Promise<GeneratedDocument>
}

/**
 * Persist generated bytes to a content store, returning a stable id + byte size.
 * Injected into the routes so the service/generator stay free of the media store.
 */
export type SaveDocumentMedia = (
  bytes: Uint8Array,
  mediaType: string,
) => Promise<{ id: string; size: number }>

// ---------------------------------------------------------------------------
// Zod request/response schemas (HTTP + validation)
// ---------------------------------------------------------------------------

export const generateFormatSchema = z.enum(GENERATE_FORMATS)

/** `POST /rpc/documents/generate` body: the format + content (+ optional name hint). */
export const generateRequestSchema = z.object({
  format: generateFormatSchema,
  content: z.string().min(1, 'content is required'),
  filename: z.string().min(1).max(200).optional(),
  layout: documentLayoutSchema.optional(),
})

/** Response of `POST /rpc/documents/generate`: where the bytes landed + how to name them. */
export interface GenerateResponse {
  /** Media store content id (`<sha256>.<ext>`) when persisted; null when persistence is off. */
  mediaId: string | null
  /** Suggested output file name (e.g. `report.docx`). */
  filename: string
  /** Canonical media type for the format. */
  mediaType: string
  /** Byte length of the produced file. */
  size: number
}
