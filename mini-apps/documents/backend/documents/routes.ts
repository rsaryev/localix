import { Hono } from 'hono'
import { documentFontSchema } from '@localixai/mini-app-sdk/document-layout'
import { fontBytes } from './generators/fonts'
import { validated } from '../validator'
import {
  defaultErrorHandler,
  jsonError,
  type MiniAppRouteContext,
} from '@localixai/mini-app-sdk/backend'
import { extractRequestSchema } from './contracts'
import {
  generateRequestSchema,
  type GenerateResponse,
  type SaveDocumentMedia,
} from './generate-contracts'
import { DOCUMENT_ERROR_STATUS, DocumentError, mapDocumentError, toErrorInfo } from './errors'
import type { DocumentsService } from './service'

/** Serialize any thrown value into a typed `{ error, code, detail }` body + status. */
function documentErrorResponse(err: unknown): {
  body: { error: string; code: string; detail?: string }
  status: number
} {
  const mapped = err instanceof DocumentError ? err : mapDocumentError(err)
  const info = toErrorInfo(mapped)
  return {
    body: { error: info.message, code: info.code, detail: info.detail },
    status: DOCUMENT_ERROR_STATUS[mapped.code],
  }
}

/** Optional route dependencies — a persistence sink for generated bytes. */
export interface DocumentsRoutesDeps {
  /** Persist generated bytes to the media store; absent → the response carries a null id. */
  saveMedia?: SaveDocumentMedia
}

/**
 * Document backend. `POST /extract` turns an office/PDF/text document (by absolute path
 * or media id) into an {@link ExtractedDocument} — Markdown for text/slides, a dataview
 * table for spreadsheets — cached content-addressed. `GET /:id` returns a cached
 * extraction by its `<hash>.json` id. `POST /generate` is the reverse: model-authored
 * content (Markdown / rows) → real docx/xlsx/pdf bytes, persisted to the media store,
 * returning the content id + a suggested filename.
 */
export function createDocumentsRoutes(service: DocumentsService, deps: DocumentsRoutesDeps = {}) {
  const app = new Hono<MiniAppRouteContext>()

  const routes = app
    .get('/font/:font/:face', async (c) => {
      const font = documentFontSchema.safeParse(c.req.param('font'))
      const face = Number(c.req.param('face'))
      if (!font.success || !Number.isInteger(face) || face < 0 || face > 3) return c.notFound()
      const bytes = await fontBytes(font.data, face)
      return new Response(new Uint8Array(bytes), {
        headers: { 'Content-Type': 'font/ttf', 'Cache-Control': 'public, max-age=86400' },
      })
    })
    .post('/render', validated('json', generateRequestSchema), async (c) => {
      try {
        const input = c.req.valid('json')
        const output = await service.generate({ ...input, format: 'pdf' })
        return new Response(output.bytes as Uint8Array<ArrayBuffer>, {
          headers: { 'Content-Type': 'application/pdf', 'Cache-Control': 'no-store' },
        })
      } catch (err) {
        const { body, status } = documentErrorResponse(err)
        return c.json(body, status as 400)
      }
    })
    .post('/extract', validated('json', extractRequestSchema), async (c) => {
      try {
        const res = await service.extract(c.req.valid('json'))
        return c.json(res)
      } catch (err) {
        const { body, status } = documentErrorResponse(err)
        return c.json(body, status as 400)
      }
    })
    .post('/generate', validated('json', generateRequestSchema), async (c) => {
      try {
        const input = c.req.valid('json')
        const gen = await service.generate(input)
        let mediaId: string | null = null
        let size = gen.bytes.byteLength
        if (deps.saveMedia) {
          const saved = await deps.saveMedia(gen.bytes, gen.mediaType)
          mediaId = saved.id
          size = saved.size
        }
        const res: GenerateResponse = {
          mediaId,
          filename: gen.suggestedFilename,
          mediaType: gen.mediaType,
          size,
        }
        return c.json(res)
      } catch (err) {
        const { body, status } = documentErrorResponse(err)
        return c.json(body, status as 400)
      }
    })
    .get('/:id', async (c) => {
      const doc = await service.get(c.req.param('id'))
      // A code is not a message: `document_not_found` in the message slot is what the client
      // would have rendered at the person.
      if (!doc)
        return jsonError(
          c,
          404,
          'not_found',
          'That extracted document is no longer cached — open the file again.',
        )
      return c.json({ document: doc })
    })

  routes.onError(defaultErrorHandler)
  return routes
}
