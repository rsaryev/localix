// `bun run check:mini-app-contract [--write] [--kit <dir>]`: is the committed mini app contract the
// one this checkout's kit carries (`mini-app-contract.mjs`)?
//
// Without `--kit` it stages the kit first (cached, `bun run mini-app-kit`); the release passes the
// kit it is about to publish. A contract that moved fails until `--write` records it, and a move
// that breaks mini apps built against the committed one is refused even then, until
// `MINI_APP_API_VERSION` moves too. `--write` also records the contract's digest for the API, which
// reports it (`GET /health`), so a kit and the Localix it was staged with name the same one.
import { execFileSync, spawnSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

import { repoRoot } from './lib/paths.mjs'
import { kitCacheRoot } from './mini-app-kit-cache.mjs'
import { CONTRACT_FILE, contractDigest, KIT_CONTRACT_FILE } from './mini-app-contract.mjs'
import { contractVerdict } from './mini-app-contract-compare.mjs'

export const CONTRACT_DIGEST_FILE = 'apps/api/src/lib/mini-app-contract.ts'

/** The API's record of the contract it implements. */
export const digestModule = (
  digest,
) => `// Generated by \`bun run check:mini-app-contract --write\` from ${CONTRACT_FILE}. Do not edit.

/**
 * The digest of the mini app contract this Localix implements; a kit staged from the same sources
 * names the same one in its \`kit.json\`.
 */
export const MINI_APP_CONTRACT = '${digest}'
`

const read = (path) => (existsSync(path) ? readFileSync(path, 'utf8') : null)

if (import.meta.main) {
  const root = repoRoot()
  const args = process.argv.slice(2)
  const write = args.includes('--write')
  const named = args[args.indexOf('--kit') + 1]
  const kitDir =
    args.includes('--kit') && named ? resolve(named) : join(root, '.turbo', 'mini-app-kit')
  if (!args.includes('--kit')) {
    execFileSync(
      'bun',
      [join(root, 'scripts/stage-mini-app-kit.mjs'), root, kitDir, `--cache=${kitCacheRoot(root)}`],
      { cwd: root, stdio: 'inherit' },
    )
  }
  const kitContract = join(kitDir, KIT_CONTRACT_FILE)
  const current = readFileSync(kitContract, 'utf8')
  const committed = read(join(root, CONTRACT_FILE))
  const verdict = committed
    ? contractVerdict(committed, current, { write })
    : { ok: write, write, breaking: [], changes: ['there is no committed contract yet'] }
  const say = (title, lines) => {
    if (lines.length) console.log(`${title}\n${lines.map((line) => `  - ${line}`).join('\n')}`)
  }
  say('Breaks mini apps built against the committed contract:', verdict.breaking)
  say('Changes:', verdict.changes)
  if (verdict.write) {
    writeFileSync(join(root, CONTRACT_FILE), current)
    writeFileSync(join(root, CONTRACT_DIGEST_FILE), digestModule(contractDigest(current)))
    console.log(`Wrote ${CONTRACT_FILE} and ${CONTRACT_DIGEST_FILE}; review the diff.`)
  }
  const recorded = read(join(root, CONTRACT_DIGEST_FILE)) ?? ''
  const digestCurrent = recorded.includes(
    `'${contractDigest(read(join(root, CONTRACT_FILE)) ?? '')}'`,
  )
  if (!verdict.ok) {
    // What moved, as text: a machine that stages the kit differently shows here how.
    const diff = spawnSync(
      'git',
      ['--no-pager', 'diff', '--no-index', '--unified=1', join(root, CONTRACT_FILE), kitContract],
      { encoding: 'utf8' },
    ).stdout
    const lines = diff.split('\n')
    console.log(lines.slice(0, 200).join('\n'))
    if (lines.length > 200) console.log(`… ${lines.length - 200} more lines`)
    console.error(
      verdict.breaking.length
        ? 'The mini app contract breaks: keep what mini apps rely on, or move MINI_APP_API_VERSION (packages/mini-app-sdk/src/manifest/primitives.ts) and write it again.'
        : 'The mini app contract moved: `bun run check:mini-app-contract --write`, then review the diff.',
    )
    process.exit(1)
  }
  if (!digestCurrent) {
    console.error(
      `${CONTRACT_DIGEST_FILE} does not name the committed contract: \`bun run check:mini-app-contract --write\`.`,
    )
    process.exit(1)
  }
  if (!verdict.write) console.log('The mini app contract is current.')
}
