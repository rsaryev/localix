// Generate the Rust half of the desktop shell <-> API runtime contract from its TypeScript source.
//
//   bun scripts/runtime-contract.mjs --write   rewrite src-tauri/src/runtime_contract.rs
//   bun scripts/runtime-contract.mjs --check   fail when the committed file is not what this renders
//
// The source of truth is `apps/api/src/lib/runtime-protocol.ts`. The frame prefix, the shutdown word,
// the environment names, the ready-frame fields and the two deadlines the shell's own timeouts must
// outlast are all spelled in both languages; before this they were two copies held together by
// comments. The generated file is committed (cargo has to see it with no step before it), and
// `check:generated` compares it with a fresh render, with no git involved, so it also catches an
// uncommitted edit on either side.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import * as protocol from '../apps/api/src/lib/runtime-protocol.ts'
import { repoRoot } from './lib/paths.mjs'

const root = repoRoot()
export const RUST_CONTRACT_FILE = join(
  root,
  'apps',
  'desktop-tauri',
  'src-tauri',
  'src',
  'runtime_contract.rs',
)

/** A Rust string literal for `text`; refuses anything that is not plain printable ASCII. */
function rustString(text) {
  if (!/^[\x20-\x7e]*$/u.test(text)) throw new Error(`Not plain ASCII: ${JSON.stringify(text)}`)
  return `"${text.replace(/\\/gu, '\\\\').replace(/"/gu, '\\"')}"`
}

const snakeCase = (name) => name.replace(/[A-Z]/gu, (letter) => `_${letter.toLowerCase()}`)

/** The text of `runtime_contract.rs` for a protocol module (the real one unless a test passes one). */
export function renderRuntimeContract(source = protocol) {
  const fields = Object.entries(source.RUNTIME_READY_FIELDS).map(
    ([name, type]) => `    pub(crate) ${snakeCase(name)}: ${type},`,
  )
  return [
    '// @generated by scripts/runtime-contract.mjs from apps/api/src/lib/runtime-protocol.ts.',
    '// Do not edit by hand: change the TypeScript, then run `bun scripts/runtime-contract.mjs --write`.',
    '// `bun run check:generated` fails when this file and the TypeScript disagree.',
    '',
    '/// The stdout line that carries the runtime endpoint once the API is serving.',
    `pub(crate) const READY_PREFIX: &str = ${rustString(source.LOCALIX_RUNTIME_READY_PREFIX)};`,
    '',
    "/// The argument that makes the API run as the shell's child.",
    `pub(crate) const DESKTOP_RUNTIME_ARG: &str = ${rustString(source.DESKTOP_RUNTIME_ARG)};`,
    '',
    "/// Written to the runtime's stdin to ask it to stop.",
    `pub(crate) const SHUTDOWN_COMMAND: &[u8] = b"${rustString(source.RUNTIME_SHUTDOWN_COMMAND).slice(1, -1)}\\n";`,
    '',
    '/// Environment the shell sets on the runtime.',
    `pub(crate) const ENV_PARENT_PID: &str = ${rustString(source.RUNTIME_ENV.parentPid)};`,
    `pub(crate) const ENV_LAUNCH_ID: &str = ${rustString(source.RUNTIME_ENV.launchId)};`,
    `pub(crate) const ENV_CLI_ENTRY: &str = ${rustString(source.RUNTIME_ENV.cliEntry)};`,
    '',
    "/// How long the runtime waits for a sibling before giving up; the shell's start budget must exceed it.",
    `pub(crate) const API_ATTACH_WAIT_MS: u128 = ${source.RUNTIME_ATTACH_WAIT_MS};`,
    "/// How long the runtime's own teardown may take; the shell's wait for `shutdown` must exceed it.",
    `pub(crate) const API_SHUTDOWN_DEADLINE_MS: u128 = ${source.RUNTIME_SHUTDOWN_DEADLINE_MS};`,
    '',
    '/// The ready-frame fields the shell reads (the frame is a full runtime endpoint; the rest is ignored).',
    '#[derive(serde::Deserialize)]',
    '#[serde(rename_all = "camelCase")]',
    'pub(crate) struct RuntimeReady {',
    ...fields,
    '}',
    '',
  ].join('\n')
}

/** `undefined` when the committed file matches the render, else a message saying how to fix it. */
export function checkRuntimeContract(source = protocol, file = RUST_CONTRACT_FILE) {
  let committed
  try {
    committed = readFileSync(file, 'utf8')
  } catch {
    committed = undefined
  }
  if (committed === renderRuntimeContract(source)) return undefined
  return `${file.slice(root.length + 1)} does not match apps/api/src/lib/runtime-protocol.ts. Run: bun scripts/runtime-contract.mjs --write`
}

function main() {
  const mode = process.argv[2]
  if (mode === '--write') {
    writeFileSync(RUST_CONTRACT_FILE, renderRuntimeContract())
    console.log(`[runtime-contract] wrote ${RUST_CONTRACT_FILE.slice(root.length + 1)}`)
  } else if (mode === '--check') {
    const problem = checkRuntimeContract()
    if (problem) {
      console.error(`[runtime-contract] ${problem}`)
      process.exitCode = 1
    } else console.log('[runtime-contract] the Rust contract matches its TypeScript source')
  } else {
    console.error('usage: runtime-contract.mjs --write | --check')
    process.exitCode = 2
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main()
